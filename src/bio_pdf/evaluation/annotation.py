"""Human annotation schema.

Annotations are the ground truth for the benchmark. They are NOT generated by
a model: a model may propose a ``draft``, but only an annotation marked
``human_verified`` (with ``status == "verified"``) counts toward the official
accuracy denominator.
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

AnnotationKind = Literal["sequence", "measurement", "unreadable"]
AnnotationStatus = Literal["draft", "verified"]


class Annotation(BaseModel):
    """One ground-truth object on one page.

    ``kind`` discriminates the fields that are meaningful:

    - ``sequence`` → ``seq_id_no`` / ``sequence`` / ``molecule_type``
    - ``measurement`` → ``metric`` / ``entity_raw`` / ``target_raw`` /
      ``value_raw`` / ``unit_raw``
    - ``unreadable`` → an object we could not read (counted in coverage,
      never silently dropped from the denominator)
    """

    model_config = ConfigDict(extra="forbid")

    annotation_id: str = Field(min_length=1)
    document_id: str = Field(min_length=1)
    page_number: int = Field(ge=1)
    kind: AnnotationKind
    human_verified: bool = False
    status: AnnotationStatus = "draft"

    # Sequence fields
    seq_id_no: str | None = None
    sequence: str | None = None
    molecule_type: str | None = None

    # Measurement fields
    metric: str | None = None
    entity_raw: str | None = None
    target_raw: str | None = None
    value_raw: str | None = None
    unit_raw: str | None = None

    # Evidence anchor
    bbox: list[float] | None = None
    note: str | None = None


__all__ = ["Annotation", "AnnotationKind", "AnnotationStatus"]